@Composable
fun LiveScreen(
    viewModel: LiveViewModel,
    initialSourceUri: String? = null
) {
    var isLoading by remember { mutableStateOf(true) }
    
    LaunchedEffect(Unit) {
        delay(150) // Brief delay to allow navigation transition to finish smoothly
        isLoading = false
    }

    if (isLoading) {
        Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                CircularProgressIndicator(color = MaterialTheme.colorScheme.primary)
                Spacer(modifier = Modifier.height(16.dp))
                Text("Memuat Live Studio...", color = MaterialTheme.colorScheme.onBackground)
            }
        }
    } else {
        LiveStreamingPage(
            viewModel = viewModel,
            initialSourceUri = initialSourceUri
        )
    }
}

private fun String?.isNull_or_blank(): Boolean = this == null || this.isBlank()

fun formatDuration(seconds: Long): String {
    val hrs = seconds / 3600
    val mins = (seconds % 3600) / 60
    val secs = seconds % 60
    return if (hrs > 0) {
        "%02d:%02d:%02d".format(hrs, mins, secs)
    } else {
        "%02d:%02d".format(mins, secs)
    }
}
